#!/usr/bin/env python3
"""Regenerate docs/results_summary.md from the result CSVs of the five experiment suites."""
from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
EXP = ROOT / "experiments"


def _fmt(v, nd):
    if isinstance(v, (float, np.floating)):
        return f"{v:.0f}" if float(v).is_integer() and abs(v) >= 1 else f"{v:.{nd}f}"
    return str(v)


def md(df, floatfmt=3):
    cols = [str(c) for c in df.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(_fmt(v, floatfmt) for v in r) + " |")
    return "\n".join(out)


def main():
    parts = ["# Results summary", "",
             "Generated by `scripts/summarize_results.py` from the CSV files in `experiments/*/data/`. Do not edit by hand.", ""]

    # exp0
    d = EXP / "exp0_falsification" / "data"
    agg = pd.read_csv(d / "exp0_agg.csv")
    p = agg.pivot(index="level", columns="structure", values="stab_boot")
    p["gap_vs_best_null"] = p["structured"] - p[["null_iso", "null_aniso"]].max(axis=1)
    parts += ["## exp0: bootstrap stability (mean pairwise ARI) by Gaussian noise level", "", md(p.reset_index()), ""]
    v = pd.read_csv(d / "exp0_verdict.csv")
    c = v.groupby("experiment").h1_supported.agg(supported="sum", conditions="count").reset_index()
    parts += ["H1 (stability separates structure from null; gap >= 0.10) supported in:", "", md(c, 0), ""]
    sc = pd.read_csv(d / "exp0_scaled_agg.csv")
    q = sc.pivot_table(index=["level", "d"], columns="structure", values="stab_boot")
    q["gap_vs_best_null"] = q["structured"] - q[["null_iso", "null_aniso"]].max(axis=1)
    parts += ["Scaled regime (n=600):", "", md(q.reset_index()), ""]

    # exp1
    r = pd.read_csv(EXP / "exp1_generalization" / "data" / "exp1_generalization_results.csv")
    t = r[r.n_train.isin([100, 1200])].groupby(["n_train", "profile", "method"]).ARI_test.mean().unstack("method").reset_index()
    parts += ["## exp1: ARI on 800 held-out rows (mean over 3 seeds)", "", md(t), ""]

    # exp2
    r = pd.read_csv(EXP / "exp2_ablation" / "data" / "exp2_ablation_results.csv")
    t = r.groupby(["variant", "profile"]).ARI.agg(["mean", "std"]).unstack("profile")
    t.columns = [f"{b}_{a}" for a, b in t.columns]
    parts += ["## exp2: ablation, ARI (mean and sd over 3 data seeds)", "", md(t.reset_index().sort_values("noisy_mean")), ""]

    # exp3
    s = pd.read_csv(EXP / "exp3_real_world_benchmarks" / "data" / "exp3_summary.csv")
    t = s.pivot_table(index=["dataset", "variant"], columns="method", values="ARI").reset_index()
    rk = s.groupby(["variant", "method"]).rank_ARI.mean().unstack("variant").reset_index()
    parts += ["## exp3: real-world ARI (mean over 5 seeds)", "", md(t), "", "Average ARI rank (1 = best):", "", md(rk, 2), ""]

    # exp4
    d = EXP / "exp4_scalability_and_sensitivity" / "data"
    sc = pd.read_csv(d / "exp4_scalability_results.csv")
    t = sc[sc.sweep == "N"].groupby(["n", "method"]).seconds.mean().unstack("method").reset_index()
    parts += ["## exp4: runtime in seconds versus N (d=100)", "", md(t), "", "Log-log slopes:", "",
              md(pd.read_csv(d / "exp4_scaling_fits.csv")), ""]
    se = pd.read_csv(d / "exp4_sensitivity_results.csv")
    t = se.groupby(["param", "value"]).ARI.mean().reset_index()
    rng = t.groupby("param").ARI.agg(lambda x: x.max() - x.min()).rename("ARI_range").reset_index()
    parts += ["Sensitivity (range of mean ARI over each parameter grid):", "", md(rng), ""]

    # ---- PCCS-specific results
    parts += ["# PCCS results", ""]
    d = EXP / "exp0_falsification" / "data"
    a = pd.read_csv(d / "exp0_pccs_auc.csv")
    t = a.pivot_table(index="predictor", columns=["task", "level"], values="auc")
    t.columns = [f"{k.replace('structured_vs_', '')}@{l}" for k, l in t.columns]
    parts += ["## exp0 (PCCS): directed AUC of stability detectors, structured vs null", "", md(t.reset_index()), ""]
    d = EXP / "exp2_ablation" / "data"
    r = pd.read_csv(d / "exp2_pccs_ablation_results.csv")
    t = r.groupby(["variant", "profile"]).ARI.agg(["mean", "std"]).unstack("profile")
    t.columns = [f"{b}_{a}" for a, b in t.columns]
    parts += ["## exp2 (PCCS): consensus ablation, ARI over 5 data seeds", "", md(t.reset_index().sort_values("noisy_mean")), ""]
    parts += ["PSI versus cluster error (Spearman):", "", md(pd.read_csv(d / "exp2_pccs_validity_stats.csv")), "",
              "Cluster error by reliability category:", "", md(pd.read_csv(d / "exp2_pccs_category_error.csv")), ""]
    d = EXP / "exp3_real_world_benchmarks" / "data"
    a = pd.read_csv(d / "exp3_pccs_vs_others.csv")
    parts += ["## exp3 (PCCS): ARI on iris, wine, breast cancer", "",
              md(a.pivot_table(index=["dataset", "variant"], columns="method", values="ARI").reset_index()), ""]
    d = EXP / "exp4_scalability_and_sensitivity" / "data"
    i = pd.read_csv(d / "exp4_pccs_interaction_summary.csv")
    parts += ["## exp4 (PCCS): largest pairwise interaction effects (global, mean over 3 seeds)", "",
              md(i.sort_values("mean", ascending=False).head(6)), "",
              f"Pairs with mean interaction >= 0.15: {int((i['mean'] >= 0.15).sum())} of {len(i)}.", "",
              "Stability (mean ARI to reference) by family and active method:", "",
              md(pd.read_csv(d / "exp4_pccs_family_stability.csv")), ""]

    out = ROOT / "docs" / "results_summary.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
